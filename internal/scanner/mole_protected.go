var moleProtectedRegexp = func() *regexp.Regexp {
	parts := make([]string, 0, len(moleProtectedGlobs))
	for _, glob := range moleProtectedGlobs {
		parts = append(parts, strings.ReplaceAll(regexp.QuoteMeta(glob), `\*`, `.*`))
	}
	return regexp.MustCompile(`^(?:` + strings.Join(parts, "|") + `)$`)
}()

// moleProtectedName is should_protect_data asked for the name and for its
// lowercase form, as Mole's Application Support pass does.
func moleProtectedName(name string) bool {
	return moleProtectedRegexp.MatchString(name) || moleProtectedRegexp.MatchString(strings.ToLower(name))
}

// Ported from tw93/Mole V1.70.0 lib/core/app_protection.sh is_critical_system_component
func isCriticalSystemComponent(name string) bool {
	lower := strings.ToLower(name)
	for _, word := range []string{"backgroundtaskmanagement", "loginitems", "systempreferences", "systemsettings", "settings",
		"preferences", "controlcenter", "biometrickit", "sfl", "tcc"} {
		if strings.Contains(lower, word) {
			return true
		}
	}
	return false
}
